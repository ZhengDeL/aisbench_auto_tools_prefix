def expand_scenarios_for_simulation(scenarios: List[Dict[str, object]]) -> Tuple[List[str], List[str]]:
    peak_min_cc = 1
    peak_max_mult = 20
    peak_data_multiplier = 4
    peak_wait = 10
    peak_ttft_default = 5.0
    peak_tpot_default = 50.0
    defaults = {
        "npu_num": "128",
        "test_type": "stream",
        "repeat": "1",
        "dataset_type": "normal",
        "prefix_num": "1",
        "repeat_rate": "0",
        "seed": "1",
        "dp": "1",
    }
    multiplier = re.search(r'^DATA_NUM_MULTIPLIER="\$\{DATA_NUM_MULTIPLIER:-(\d+)\}"\s*$', read_text(RUN_SCRIPT), flags=re.M)
    if multiplier is None:
        raise ValueError("fixed DATA_NUM_MULTIPLIER not found in run_perf_scenarios.sh")
    data_num_multiplier = int(os.environ.get("DATA_NUM_MULTIPLIER") or multiplier.group(1))
    if data_num_multiplier <= 0:
        raise ValueError("DATA_NUM_MULTIPLIER must be a positive integer")
    combo_lines: List[str] = []
    peak_lines: List[str] = []
    for sc in scenarios:
        name = str(sc["name"])
        input_len = sc.get("input_len", "512")
        output_len = sc.get("output_len", "128")
        request_rate = sc.get("request_rate", "0")
        concurrency_values = sc.get("concurrency", [1])
        assert isinstance(concurrency_values, list)
        special_keys = {
            "name",
            "input_len",
            "output_len",
            "concurrency",
            "request_rate",
            "ttft_limit",
            "tpot_limit",
            "peak_min_cc",
            "peak_max_cc",
            "peak_data_multiplier",
            "peak_wait",
        }
        extra = {k: v for k, v in sc.items() if k not in special_keys}
        fixed_concs = [c for c in concurrency_values if c != "max"]
        has_peak = "max" in concurrency_values
        for conc in fixed_concs:
            data_num = str(extra["data_num"]) if "data_num" in extra else str(int(str(conc)) * data_num_multiplier)
            params = {
                "input_len": input_len,
                "output_len": output_len,
                "concurrency": str(conc),
                "request_rate": request_rate,
                "data_num": data_num,
            }
            for k, v in defaults.items():
                if k not in extra:
                    params[k] = v
            params.update(extra)
            for pk in ["ttft_limit", "tpot_limit", "peak_min_cc", "peak_max_cc", "peak_data_multiplier", "peak_wait"]:
                params.pop(pk, None)
            cmd_str = " ".join(f"--{k} {v}" for k, v in params.items())
            combo_lines.append(f"{name}_c{conc}|{cmd_str}")
        if has_peak:
            ttft = sc.get("ttft_limit", peak_ttft_default)
            tpot = sc.get("tpot_limit", peak_tpot_default)
            max_cc = sc.get("peak_max_cc", int(str(fixed_concs[0])) * peak_max_mult if fixed_concs else peak_min_cc * peak_max_mult)
            min_cc = sc.get("peak_min_cc", peak_min_cc)
            step = sc.get("peak_data_multiplier", peak_data_multiplier)
            wait = sc.get("peak_wait", peak_wait)
            forward_str = " ".join(f"--{k} {v}" for k, v in extra.items())
            peak_lines.append(f"{name}_peak|{input_len}|{output_len}|{min_cc}|{max_cc}|{step}|{request_rate}|{ttft}|{tpot}|{wait}|{forward_str}")
    return combo_lines, peak_lines


